-- CONFIA: prototipo relacional executavel em PostgreSQL.
-- Os dados brutos sao efemeros; as tabelas operacionais guardam hashes, nunca CPF/nome.
CREATE TABLE lojista (
  id_lojista BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  cnpj_hash CHAR(64) NOT NULL UNIQUE,
  hora_abertura TIME NOT NULL,
  hora_fechamento TIME NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lojista BIGINT NOT NULL REFERENCES lojista,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  papel TEXT NOT NULL CHECK (papel IN ('LOJISTA','ANALISTA'))
);
CREATE TABLE conta_recebedora (
  id_conta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lojista BIGINT NOT NULL REFERENCES lojista,
  chave_pix_hash CHAR(64) NOT NULL UNIQUE,
  apelido TEXT NOT NULL,
  canal_padrao TEXT NOT NULL CHECK (canal_padrao IN ('PRESENCIAL','ECOMMERCE')),
  UNIQUE (id_conta, id_lojista)
);
CREATE TABLE pagador (
  id_pagador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lojista BIGINT NOT NULL REFERENCES lojista,
  documento_hash CHAR(64) NOT NULL,
  nome_hash CHAR(64),
  primeiro_pagamento_em TIMESTAMPTZ,
  ultimo_pagamento_em TIMESTAMPTZ,
  qtd_pagamentos INTEGER NOT NULL DEFAULT 0 CHECK (qtd_pagamentos >= 0),
  qtd_contestacoes INTEGER NOT NULL DEFAULT 0 CHECK (qtd_contestacoes >= 0),
  UNIQUE (id_lojista, documento_hash),
  UNIQUE (id_pagador, id_lojista)
);
CREATE TABLE ingestao_webhook (
  id_ingestao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  psp TEXT NOT NULL,
  origem_autenticada BOOLEAN NOT NULL,
  confirmado_na_api BOOLEAN NOT NULL DEFAULT FALSE,
  payload JSONB NOT NULL,
  situacao_processamento TEXT NOT NULL DEFAULT 'PENDENTE' CHECK (situacao_processamento IN ('PENDENTE','PROCESSADO','REJEITADO')),
  recebido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  expurgar_em TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '7 days')
);
CREATE TABLE pagamento (
  id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conta BIGINT NOT NULL,
  id_lojista BIGINT NOT NULL REFERENCES lojista,
  id_pagador BIGINT NOT NULL,
  psp TEXT NOT NULL,
  end_to_end_id TEXT NOT NULL,
  txid TEXT,
  canal TEXT NOT NULL CHECK (canal IN ('PRESENCIAL','ECOMMERCE')),
  valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
  ocorrido_em TIMESTAMPTZ NOT NULL,
  registrado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  situacao_entrega TEXT NOT NULL DEFAULT 'RETIDA' CHECK (situacao_entrega IN ('RETIDA','LIBERADA','DEVOLVIDA','CONTESTADA')),
  FOREIGN KEY (id_pagador, id_lojista) REFERENCES pagador(id_pagador, id_lojista),
  FOREIGN KEY (id_conta, id_lojista) REFERENCES conta_recebedora(id_conta, id_lojista),
  UNIQUE (psp, end_to_end_id)
);
CREATE TABLE cobranca_esperada (
  id_cobranca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conta BIGINT NOT NULL REFERENCES conta_recebedora,
  txid TEXT NOT NULL,
  valor_esperado NUMERIC(12,2) NOT NULL CHECK (valor_esperado > 0),
  referencia_pedido TEXT NOT NULL,
  expira_em TIMESTAMPTZ NOT NULL,
  UNIQUE (id_conta, txid)
);
CREATE TABLE regra (
  id_regra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL,
  versao INTEGER NOT NULL CHECK (versao > 0),
  descricao TEXT NOT NULL,
  peso SMALLINT NOT NULL CHECK (peso BETWEEN 0 AND 100),
  ativa BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (codigo, versao)
);
CREATE TABLE analise_risco (
  id_analise BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pagamento BIGINT NOT NULL UNIQUE REFERENCES pagamento,
  veredito TEXT NOT NULL CHECK (veredito IN ('APROVADO','EM_ANALISE','RECUSADO')),
  score SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 100),
  degradada BOOLEAN NOT NULL DEFAULT FALSE,
  latencia_ms INTEGER NOT NULL CHECK (latencia_ms >= 0),
  versao_catalogo INTEGER NOT NULL,
  analisado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (NOT (degradada AND veredito = 'RECUSADO'))
);
CREATE TABLE sinal_apurado (
  id_sinal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_analise BIGINT NOT NULL REFERENCES analise_risco,
  id_regra BIGINT NOT NULL REFERENCES regra,
  disparou BOOLEAN NOT NULL,
  contribuicao SMALLINT NOT NULL CHECK (contribuicao BETWEEN 0 AND 100),
  detalhe JSONB NOT NULL DEFAULT '{}'::jsonb,
  UNIQUE (id_analise, id_regra)
);
CREATE TABLE alerta (
  id_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_analise BIGINT NOT NULL UNIQUE REFERENCES analise_risco,
  situacao TEXT NOT NULL CHECK (situacao IN ('ABERTO','FECHADO')),
  aberto_em TIMESTAMPTZ NOT NULL,
  fechado_em TIMESTAMPTZ
);
CREATE TABLE desfecho (
  id_desfecho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_alerta BIGINT NOT NULL UNIQUE REFERENCES alerta,
  rotulo TEXT NOT NULL CHECK (rotulo IN ('FRAUDE','LEGITIMO')),
  justificativa TEXT NOT NULL,
  registrado_em TIMESTAMPTZ NOT NULL
);
CREATE TABLE devolucao (
  id_devolucao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pagamento BIGINT NOT NULL REFERENCES pagamento,
  origem TEXT NOT NULL CHECK (origem IN ('MED','SOLICITADA_LOJISTA')),
  valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
  situacao TEXT NOT NULL CHECK (situacao IN ('PENDENTE','CONCLUIDA','FALHOU')),
  solicitada_em TIMESTAMPTZ NOT NULL,
  concluida_em TIMESTAMPTZ
);
CREATE TABLE notificacao (
  id_notificacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pagamento BIGINT NOT NULL REFERENCES pagamento,
  id_usuario BIGINT NOT NULL REFERENCES usuario,
  canal_envio TEXT NOT NULL,
  conteudo TEXT NOT NULL,
  enviada_em TIMESTAMPTZ NOT NULL
);
CREATE TABLE auditoria (
  id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lojista BIGINT NOT NULL REFERENCES lojista,
  entidade TEXT NOT NULL,
  id_entidade BIGINT NOT NULL,
  acao TEXT NOT NULL,
  ator TEXT NOT NULL,
  payload_hash CHAR(64) NOT NULL,
  hash_anterior CHAR(64),
  ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_pagamento_pagador_tempo ON pagamento(id_pagador, ocorrido_em DESC);
CREATE INDEX ix_pagamento_conta_tempo ON pagamento(id_conta, ocorrido_em DESC);
CREATE INDEX ix_pagamento_retida ON pagamento(id_pagamento) WHERE situacao_entrega = 'RETIDA';
CREATE INDEX ix_alerta_aberto ON alerta(id_alerta) WHERE situacao = 'ABERTO';
CREATE INDEX ix_ingestao_payload ON ingestao_webhook USING GIN(payload);
CREATE INDEX ix_ingestao_expurgo ON ingestao_webhook(expurgar_em);
CREATE INDEX ix_sinal_regra ON sinal_apurado(id_regra, disparou);
CREATE INDEX ix_analise_tempo ON analise_risco(analisado_em DESC);
CREATE INDEX ix_devolucao_pagamento_origem ON devolucao(id_pagamento, origem);
